#!/usr/bin/env python3
"""Assemble generation tasks for converse.py from public prompt sets. Only the user side is taken;
the ternary model writes every reply.

  build_tasks.py SRC_DIR OUT.jsonl [--kimi 2000] [--dahoas 400] ...

SRC_DIR layout: kimi/, dahoas/, fitness/, upload/, usaid/, ppa/, y1xing/ (missing ones are skipped).
"""
import argparse, collections, csv, glob, json, os, random, re

ap = argparse.ArgumentParser()
ap.add_argument("src"); ap.add_argument("out")
ap.add_argument("--kimi", type=int, default=2000); ap.add_argument("--dahoas", type=int, default=400)
ap.add_argument("--fitness", type=int, default=100); ap.add_argument("--upload", type=int, default=600)
ap.add_argument("--leetcode", type=int, default=400); ap.add_argument("--mcq", type=int, default=400)
ap.add_argument("--grading", type=int, default=40)
ap.add_argument("--max-chars", type=int, default=12000); ap.add_argument("--seed", type=int, default=1)
a = ap.parse_args()
rnd = random.Random(a.seed)
J = lambda *p: os.path.join(a.src, *p)
tasks, stats = [], collections.Counter()


def add(prefix, turns, system=None, thinking=None):
    turns = [t.strip() for t in turns if isinstance(t, str) and t.strip()]
    if not turns or sum(len(t) for t in turns) + len(system or "") > a.max_chars:
        stats[prefix + " skipped"] += 1
        return
    t = {"id": f"{prefix}-{stats[prefix]:05d}", "thinking": rnd.random() < 0.3 if thinking is None else thinking, "turns": turns}
    if system:
        t["system"] = system.strip()
    tasks.append(t); stats[prefix] += 1


def pq_rows(path, cols):
    import pyarrow.parquet as pq
    return pq.read_table(path, columns=cols).to_pylist()


# --- Kimi MTP dataset: conversations regenerated by another model; keep system + human turns of text-only samples
p = J("kimi", "data", "train-00000-of-00001.jsonl")
if os.path.exists(p) and a.kimi:
    BAD = re.compile(r"<\|tool_call|<\|im_|<\|media|image_url|<image>|tool_calls_section", re.I)
    by_src = collections.defaultdict(list)
    n_seen = collections.Counter()
    with open(p, encoding="utf-8") as f:
        for line in f:
            try:
                r = json.loads(line)
            except Exception:
                continue
            src = r.get("source", "?")
            conv = r.get("conversations") or []
            if "llava" in src or any(not isinstance(t.get("value"), str) for t in conv):
                continue
            sys_ = " ".join(t["value"] for t in conv if t["from"] == "system")
            human = [t["value"] for t in conv if t["from"] == "human"][:2]
            if not human or BAD.search(sys_ + " ".join(human)) or "tool" in src.lower() or "function" in src.lower():
                continue
            n_seen[src] += 1
            item, cap = (sys_, human), a.kimi                     # reservoir sample per source
            if len(by_src[src]) < cap:
                by_src[src].append(item)
            elif (k := rnd.randrange(n_seen[src])) < cap:
                by_src[src][k] = item
    # proportional to sqrt(source size), so the largest source does not swamp the rest
    w = {s: n ** 0.5 for s, n in n_seen.items()}
    for s, items in by_src.items():
        for sys_, human in rnd.sample(items, min(len(items), round(a.kimi * w[s] / sum(w.values())))):
            add("kimi-" + re.sub(r"\W+", "", s)[:12], human, sys_ or None)
    stats["kimi sources seen"] = len(n_seen)

# --- Dahoas rl-prompt-dataset: "Human: ... Assistant: ..." transcripts; keep the human turns
for f in glob.glob(J("dahoas", "data", "train-*.parquet")):
    rows = pq_rows(f, ["prompt"]) if a.dahoas else []
    for r in rnd.sample(rows, min(len(rows), a.dahoas * 2)):
        human = [h.strip() for h in re.findall(r"Human:(.*?)(?=\n\s*Assistant:|\Z)", r["prompt"], flags=re.S)][:2]
        if stats["dahoas"] < a.dahoas:
            add("dahoas", human)

# --- fitness Q&A
for f in glob.glob(J("fitness", "*.json")):
    rows = json.load(open(f, encoding="utf-8"))
    for r in rnd.sample(rows, min(len(rows), a.fitness)):
        add("fitness", [r.get("instruction", "")], "You are a friendly health and fitness coach. Keep advice practical.")

# --- uploaded Prompt_Engineering.parquet
for f in glob.glob(J("upload", "*.parquet")):
    rows = pq_rows(f, ["Prompt"])
    for r in rnd.sample(rows, min(len(rows), a.upload)):
        add("pe", [r["Prompt"]])

# --- Usaid LeetCode-style questions, as coding tasks with a scripted follow-up
LANGS = ["Python", "Python", "Python", "TypeScript", "Go", "Rust", "C#", "Java", "C++", "JavaScript"]
FOLLOW = ["What is the time and space complexity? Is there a faster approach?",
          "Add a few test cases, including edge cases, and walk through one of them.",
          "Now rewrite it without recursion, or explain why that is not needed.",
          "Explain the key idea to someone who has not seen this pattern before.",
          "What happens with empty input or very large input? Make it robust."]
for f in glob.glob(J("usaid", "*.csv")):
    rows = list(csv.DictReader(open(f, encoding="utf-8", errors="replace")))
    for r in rnd.sample(rows, min(len(rows), a.leetcode)):
        q = r.get("Question", "")
        add("leet", [f"{q}\n\nSolve this in {rnd.choice(LANGS)}.", rnd.choice(FOLLOW)],
            rnd.choice([None, "You are a concise coding assistant.", "You are a patient programming tutor."]),
            thinking=r.get("Difficulty") == "Hard" or rnd.random() < 0.3)

# --- Prompt-Pool-Agent: multiple-choice reasoning questions
rows = []
for f in glob.glob(J("ppa", "data", "*_test-*.parquet")):
    rows += pq_rows(f, ["question", "options"])
for r in rnd.sample(rows, min(len(rows), a.mcq)):
    opts = r.get("options") or []
    q = r["question"] + ("\n" + "\n".join(f"{chr(65 + i)}. {o}" for i, o in enumerate(opts)) if opts else "")
    add("mcq", [q + "\n\nGive your answer and a short justification."], thinking=rnd.random() < 0.6)

# --- y1xing answer-grading prompts (highly repetitive, so only a few)
for f in glob.glob(J("y1xing", "**", "*.parquet"), recursive=True):
    rows = pq_rows(f, ["instruction", "input"])
    for r in rnd.sample(rows, min(len(rows), a.grading)):
        add("grade", [r["input"]], r["instruction"], thinking=False)

rnd.shuffle(tasks)
with open(a.out, "w", encoding="utf-8") as f:
    for t in tasks:
        f.write(json.dumps(t, ensure_ascii=False) + "\n")
n_turns = sum(len(t["turns"]) for t in tasks)
print(f"{len(tasks)} tasks, {n_turns} turns, thinking on {sum(t['thinking'] for t in tasks)}")
for k, v in sorted(stats.items()):
    print(f"  {k}: {v}")
